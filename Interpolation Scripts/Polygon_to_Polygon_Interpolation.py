def pack_upper_tri(M: np.ndarray) -> torch.Tensor:
    vals = []
    n = M.shape[0]
    for r in range(n):
        for c in range(r, n):
            vals.append(M[r, c])
    return torch.tensor(vals, dtype=torch.float32, device=DEVICE).unsqueeze(0)

def _to_noise_tensor(noise_np) -> torch.Tensor:
    """Ensure noise is (1,1,44,44) torch on DEVICE."""
    arr = np.asarray(noise_np, dtype=np.float32)
    if arr.ndim == 2:
        arr = arr[None, None, ...]
    elif arr.ndim == 3:
        arr = arr[None, ...]
    return torch.tensor(arr, device=DEVICE)

