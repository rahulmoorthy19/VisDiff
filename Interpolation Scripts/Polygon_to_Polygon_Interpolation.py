# ---------------------- Diffusion Schedule ----------------------
class Schedule:
    def __init__(self, sigmas: torch.FloatTensor):
        self.sigmas = sigmas
    def __getitem__(self, i) -> torch.FloatTensor:
        return self.sigmas[i]
    def __len__(self) -> int:
        return len(self.sigmas)
    def sample_batch(self, x0: torch.FloatTensor) -> torch.FloatTensor:
        return self[torch.randint(len(self), (x0.shape[0],))].to(x0)
    def sample_sigmas(self, steps: int) -> torch.FloatTensor:
        indices = list((len(self) * (1 - np.arange(0, steps)/steps)).round().astype(np.int64) - 1)
        return self[indices + [0]]

class ScheduleLogLinear(Schedule):
    def __init__(self, N: int, sigma_min: float=0.02, sigma_max: float=10):
        super().__init__(torch.logspace(math.log10(sigma_min), math.log10(sigma_max), N))

def pairwise(iterable):
    a, b = tee(iterable)
    next(b, None)
    return zip(a, b)

# ---------------------- Sampler ----------------------
@torch.no_grad()
def samples(model, condition, sigmas, gam, mu, xt, batchsize):
    """
    Model forward: model(xt, sig, visibility=condition, ...)
    If xt is provided, denoise starting from that; else draw Gaussian start.
    Returns final xt (SDF) and the start noise (for the None-xt case).
    """
    start = None
    if xt is None:
        xt = (torch.randn((batchsize, 1, 44, 44), device=DEVICE) * sigmas[0]).to(DEVICE)
        start = xt.clone()
    eps_prev = None
    for i, (sig, sig_prev) in enumerate(pairwise(sigmas)):
        eps = model(xt, sig.to(DEVICE), visibility=condition, encoder_hidden_states=None, output_dict=False)
        eps_av = eps if (i == 0 or eps_prev is None) else (eps * gam + eps_prev * (1 - gam))
        eps_prev = eps
        sig_p = (sig_prev/sig**mu)**(1/(1-mu))
        eta = (sig_prev**2 - sig_p**2).sqrt()
        xt = xt - (sig - sig_p) * eps_av + eta * torch.randn_like(xt)
    return xt, start

# ---------------------- Visibility (same as your snippet) ----------------------
class Visibility_Calculator:
    def line_segments_intersect(self, seg1, seg2):
        p1, p2 = np.array(seg1[0]), np.array(seg1[1])
        q1, q2 = np.array(seg2[0]), np.array(seg2[1])
        r = p2 - p1
        s = q2 - q1
        denominator = np.cross(r, s)
        if np.isclose(denominator, 0):
            return False
        t_numer = np.cross(q1 - p1, s)
        u_numer = np.cross(q1 - p1, r)
        t = t_numer / denominator
        u = u_numer / denominator
        return (0 <= t <= 1) and (0 <= u <= 1)

    def line_outside_polygon_non_valid(self, line, polygon):
        length = line.length
        midpoint = line.interpolate(length / 2)
        return not polygon.contains(midpoint)

    def process_row(self, args):
        row_index, coords, poly = args
        visibility_row = np.zeros(len(coords))
        for j in range(row_index + 1, len(coords)):
            if j - row_index == 1 or (row_index == 0 and j == len(coords) - 1):
                continue
            flag = True
            line = LineString([coords[row_index], coords[j]])
            for x in range(coords.shape[0]):
                if x != row_index and x != j and (x+1) % len(coords) != row_index and (x+1) % len(coords) != j:
                    edge = LineString([coords[x], coords[(x+1) % len(coords)]])
                    if self.line_segments_intersect(list(line.coords), list(edge.coords)) and not line.touches(edge):
                        flag = False
                        break
            if flag and self.line_outside_polygon_non_valid(line, poly):
                flag = False
            if flag:
                visibility_row[j] = 1
        return visibility_row

    def visibility_matrix_generator(self, coords):
        poly = Polygon(coords)
        n = len(coords)
        vg = np.zeros((n, n))
        np.fill_diagonal(vg, 1)
        vg += np.diag(np.ones(n-1), k=1)
        vg += np.diag(np.ones(n-1), k=-1)
        vg[0, -1] = vg[-1, 0] = 1

        args_list = [(i, coords, poly) for i in range(n)]
        pool = Pool()
        results = pool.map(self.process_row, args_list)
        pool.close(); pool.join()

        upper = np.zeros((n, n))
        for i, row in enumerate(results):
            upper[i] = row
        vg += upper + upper.T
        return (vg > 0.5).astype(np.float32)

# ---------------------- SDF → polygon initializations ----------------------
def _interp_to_n(points, n=25):
    """Resample a polyline to exactly n points (no SciPy dependency)."""
    if points.shape[0] == n:
        return points
    d = np.cumsum(np.linalg.norm(np.diff(points, axis=0), axis=1))
    d = np.insert(d, 0, 0.0)
    t = np.linspace(0.0, d[-1], n)
    x = np.interp(t, d, points[:, 0])
    y = np.interp(t, d, points[:, 1])
    return np.stack([x, y], axis=-1)

def sdf_polygon_generation(sdf: np.ndarray, band=0.1, target_n=25, scale=0.05) -> torch.Tensor:
    """
    Extract a |sdf|<band contour, simplify to ~target_n (Visvalingam–Whyatt),
    resample to exactly target_n if needed, then build cyclic + reversed variants.
    Returns (M, target_n, 2) tensor.
    """
    mask = ((sdf > -band) & (sdf < band)).astype(np.uint8) * 255
    contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    if not contours:
        # small fallback square
        pts = np.array([[0.3, 0.3], [0.3, -0.3], [-0.3, -0.3], [-0.3, 0.3]], np.float32)
    else:
        largest = max(contours, key=cv2.contourArea)
        pts = np.array([p[0] for p in largest], dtype=np.float32)
        simp = vw.Simplifier(pts).simplify(number=target_n)
        pts = simp * scale
        if pts.shape[0] < target_n:
            pts = _interp_to_n(pts, n=target_n)

    cands = []
    for k in range(len(pts)):
        cands.append(np.roll(pts, k, axis=0))
        cands.append(np.roll(pts[::-1], k, axis=0))
    return torch.tensor(np.stack(cands, axis=0), dtype=torch.float32)

